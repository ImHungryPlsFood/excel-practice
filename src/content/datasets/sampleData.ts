import { SAMPLE_DATASETS } from '@/content/sandbox/sampleDatasets';

/*
 * 가상 실무 데이터셋 (CARD-04E, MASTER_PROMPT §10, R-10.01~R-10.14).
 * 문제를 만들 때 가져다 쓰는 독창적인 가상 데이터 10종이다. 실존 기업·인물, 전화번호·이메일·주민등록번호 형식의 값은
 * 쓰지 않는다(verifyDatasets가 점검한다). 사람은 성을 뺀 가상의 이름만 쓴다.
 * 데이터는 단순하되 지나치게 규칙적이지 않게 만든다(숫자가 모두 같거나 일정하게 늘어나지 않는다).
 * 판매 내역·상품 재고·출석 기록 3종은 연습실 샘플(sandbox/sampleDatasets.ts)을 그대로 쓴다.
 * 셀 값은 사용자가 입력하는 원문 그대로다('='로 시작하면 수식).
 */

export type DatasetRows = readonly (readonly string[])[];

export interface ContentDataset {
  id: string;
  title: string;
  /** 이 데이터셋이 채우는 요구사항 (추적표 R-10.xx) */
  requirement: string;
  /** 시트 이름 → 행 우선 원문. 시트가 둘 이상이면 여러 시트로 나뉜 자료다. */
  sheets: Readonly<Record<string, DatasetRows>>;
  /** 일부러 넣은 데이터 문제(빈 셀·중복 행 등). 오류가 섞인 데이터에만 있다. */
  flaws?: readonly ('BLANK_CELL' | 'DUPLICATE_ROW' | 'INCONSISTENT_LABEL')[];
}

const REQUIREMENT_OF_SANDBOX: Readonly<Record<string, string>> = {
  sales: 'R-10.01',
  inventory: 'R-10.02',
  attendance: 'R-10.05',
};

const fromSandbox: ContentDataset[] = SAMPLE_DATASETS.flatMap((dataset) => {
  const requirement = REQUIREMENT_OF_SANDBOX[dataset.id];
  return requirement === undefined
    ? []
    : [{ id: dataset.id, title: dataset.title, requirement, sheets: { Sheet1: dataset.rows } }];
});

